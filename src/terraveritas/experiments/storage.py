"""Result storage for AI-repair generation records.

Layout: datasets/experiments/<experiment_id>/records/<case_id>.json, plus
a manifest.json per experiment summarizing the matrix cells and record
count. Serialization is a plain, explicit round-trip — no generic
reflection-based deserializer — so a schema change surfaces as a clear
failure here rather than a silently wrong reconstruction.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, is_dataclass
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Any

from terraveritas.models.baseline import BaselineConclusion, ScannerOnlyBaseline
from terraveritas.models.diff import (
    DifferentialResult,
    NewFinding,
    PersistentFinding,
    RelocatedFinding,
    RemovedFinding,
)
from terraveritas.models.experiment import HumanLabel, RepairRecord, SystemConfiguration
from terraveritas.models.finding import Finding, FindingOutcome, ScanResult, ScanStatus
from terraveritas.models.invariant import InvariantResult, InvariantStatus
from terraveritas.models.oracle import Classification, Confidence, OracleVerdict
from terraveritas.models.plan import PlannedResourceChange, PlanResult, PlanStatus
from terraveritas.security import redact_secrets


def _to_jsonable(obj: Any) -> Any:
    if is_dataclass(obj) and not isinstance(obj, type):
        return {k: _to_jsonable(v) for k, v in asdict(obj).items()}
    if isinstance(obj, Enum):
        return obj.value
    if isinstance(obj, datetime):
        return obj.isoformat()
    if isinstance(obj, list):
        return [_to_jsonable(v) for v in obj]
    if isinstance(obj, dict):
        return {k: _to_jsonable(v) for k, v in obj.items()}
    return obj


def record_to_dict(record: RepairRecord) -> dict[str, Any]:
    """Lossless serialization — deliberately NOT redacted, so a record
    loaded from disk can still be used for legitimate in-memory
    re-analysis (e.g. re-running the oracle). Redaction is applied only at
    the point of writing to disk, in save_record — see its docstring."""
    result: dict[str, Any] = _to_jsonable(record)
    return result


_ID_SEGMENT_PATTERN = re.compile(r"^[A-Za-z0-9._-]+$")


def _validate_path_segment(value: str, *, field_name: str) -> None:
    """Rejects anything that isn't a plain filename-safe segment — no path
    separators, no `..`, no absolute-path leakage. experiment_id and
    case_id are used directly as path components; without this check a
    value like "../../../etc/passwd" would escape base_dir entirely via
    Path's `/` operator, which does not sanitize `..` segments. Today both
    values are generated by this project's own identifiers.py, but this
    function defends the storage boundary itself rather than trusting every
    future caller to pass already-safe values."""
    if value in ("", ".", "..") or not _ID_SEGMENT_PATTERN.match(value):
        raise ValueError(f"{field_name} is not a safe path segment: {value!r}")


def save_record(record: RepairRecord, *, base_dir: Path) -> Path:
    """Redaction is applied here, at the point of writing a record to disk
    — this is the "report" the credential-exposure requirement is about.
    record_to_dict() itself stays lossless for in-memory use."""
    _validate_path_segment(record.experiment_id, field_name="experiment_id")
    _validate_path_segment(record.case_id, field_name="case_id")

    records_dir = base_dir / record.experiment_id / "records"
    records_dir.mkdir(parents=True, exist_ok=True)
    path = records_dir / f"{record.case_id}.json"
    redacted = redact_secrets(record_to_dict(record))
    path.write_text(json.dumps(redacted, indent=2, sort_keys=True))
    return path


def _finding_from_dict(d: dict[str, Any]) -> Finding:
    return Finding(
        scanner_name=d["scanner_name"],
        scanner_version=d["scanner_version"],
        rule_id=d["rule_id"],
        outcome=FindingOutcome(d["outcome"]),
        file_path=d["file_path"],
        description=d["description"],
        raw_evidence=d["raw_evidence"],
        scan_timestamp=datetime.fromisoformat(d["scan_timestamp"]),
        severity=d.get("severity"),
        resource_id=d.get("resource_id"),
        resource_type=d.get("resource_type"),
        line_start=d.get("line_start"),
        line_end=d.get("line_end"),
    )


def _scan_result_from_dict(d: dict[str, Any]) -> ScanResult:
    return ScanResult(
        scanner_name=d["scanner_name"],
        scanner_version=d["scanner_version"],
        target_path=d["target_path"],
        status=ScanStatus(d["status"]),
        findings=[_finding_from_dict(f) for f in d["findings"]],
        unparseable_files=d.get("unparseable_files", []),
        command=d.get("command", []),
        started_at=datetime.fromisoformat(d["started_at"]) if d.get("started_at") else None,
        finished_at=datetime.fromisoformat(d["finished_at"]) if d.get("finished_at") else None,
        exit_code=d.get("exit_code"),
        error_message=d.get("error_message"),
    )


def _differential_from_dict(d: dict[str, Any]) -> DifferentialResult:
    return DifferentialResult(
        scanner_name=d["scanner_name"],
        removed=[
            RemovedFinding(
                before=_finding_from_dict(r["before"]),
                resource_still_present_in_after=r["resource_still_present_in_after"],
                same_identity_now_passes=r["same_identity_now_passes"],
            )
            for r in d["removed"]
        ],
        persistent=[
            PersistentFinding(
                before=_finding_from_dict(p["before"]), after=_finding_from_dict(p["after"])
            )
            for p in d["persistent"]
        ],
        new=[NewFinding(after=_finding_from_dict(n["after"])) for n in d["new"]],
        relocated=[
            RelocatedFinding(
                before=_finding_from_dict(r["before"]),
                after=_finding_from_dict(r["after"]),
                note=r["note"],
            )
            for r in d["relocated"]
        ],
    )


def _oracle_verdict_from_dict(d: dict[str, Any] | None) -> OracleVerdict | None:
    if d is None:
        return None
    return OracleVerdict(
        classification=Classification(d["classification"]),
        confidence=Confidence(d["confidence"]),
        invariant_id=d["invariant_id"],
        resource_address=d["resource_address"],
        evidence_used=d["evidence_used"],
        reasons=d["reasons"],
        remaining_uncertainty=d["remaining_uncertainty"],
    )


def _human_label_from_dict(d: dict[str, Any] | None) -> HumanLabel | None:
    if d is None:
        return None
    return HumanLabel(
        label=d["label"],
        annotator=d["annotator"],
        labeled_at=datetime.fromisoformat(d["labeled_at"]),
        notes=d.get("notes", ""),
    )


def _planned_resource_change_from_dict(d: dict[str, Any]) -> PlannedResourceChange:
    return PlannedResourceChange(
        address=d["address"],
        resource_type=d["resource_type"],
        resource_name=d["resource_name"],
        provider_name=d["provider_name"],
        actions=d["actions"],
        after=d["after"],
        after_unknown_keys=d["after_unknown_keys"],
    )


def _plan_result_from_dict(d: dict[str, Any] | None) -> PlanResult | None:
    if d is None:
        return None
    return PlanResult(
        target_path=d["target_path"],
        status=PlanStatus(d["status"]),
        terraform_version=d.get("terraform_version"),
        resource_changes=[
            _planned_resource_change_from_dict(rc) for rc in d.get("resource_changes", [])
        ],
        raw_plan_json=d.get("raw_plan_json"),
        commands_run=d.get("commands_run", []),
        error_message=d.get("error_message"),
        started_at=datetime.fromisoformat(d["started_at"]) if d.get("started_at") else None,
        finished_at=datetime.fromisoformat(d["finished_at"]) if d.get("finished_at") else None,
    )


def _invariant_result_from_dict(d: dict[str, Any] | None) -> InvariantResult | None:
    if d is None:
        return None
    return InvariantResult(
        invariant_id=d["invariant_id"],
        resource_address=d["resource_address"],
        status=InvariantStatus(d["status"]),
        violated_conditions=d.get("violated_conditions", []),
        reason=d.get("reason", ""),
        evidence=d.get("evidence", {}),
    )


def _scanner_baseline_from_dict(d: dict[str, Any] | None) -> ScannerOnlyBaseline | None:
    if d is None:
        return None
    return ScannerOnlyBaseline(
        narrow_conclusion=BaselineConclusion(d["narrow_conclusion"]),
        narrow_reason=d["narrow_reason"],
        broad_conclusion=BaselineConclusion(d["broad_conclusion"]),
        broad_reason=d["broad_reason"],
    )


def load_record(path: Path) -> RepairRecord:
    d = json.loads(path.read_text())
    return RepairRecord(
        experiment_id=d["experiment_id"],
        case_id=d["case_id"],
        generated_at=datetime.fromisoformat(d["generated_at"]),
        original_terraform=d["original_terraform"],
        original_terraform_sha256=d["original_terraform_sha256"],
        original_security_issue_rule_id=d["original_security_issue_rule_id"],
        original_security_issue_description=d["original_security_issue_description"],
        vulnerability_class=d["vulnerability_class"],
        ai_model=d["ai_model"],
        model_version=d["model_version"],
        prompt_template_id=d["prompt_template_id"],
        rendered_prompt=d["rendered_prompt"],
        system_configuration=SystemConfiguration(**d["system_configuration"]),
        raw_ai_output=d["raw_ai_output"],
        extracted_terraform=d["extracted_terraform"],
        before_scan=_scan_result_from_dict(d["before_scan"]),
        after_scan=_scan_result_from_dict(d["after_scan"]),
        differential=_differential_from_dict(d["differential"]),
        before_plan_status=PlanStatus(d["before_plan_status"]),
        after_plan_status=PlanStatus(d["after_plan_status"]),
        oracle_verdict=_oracle_verdict_from_dict(d["oracle_verdict"]),
        human_label=_human_label_from_dict(d["human_label"]),
        environment=d.get("environment", {}),
        # .get(), not d[...]: additive fields (Prompt 14 fix for H2) absent
        # from any record written before this change.
        before_plan=_plan_result_from_dict(d.get("before_plan")),
        after_plan=_plan_result_from_dict(d.get("after_plan")),
        before_invariant=_invariant_result_from_dict(d.get("before_invariant")),
        after_invariant=_invariant_result_from_dict(d.get("after_invariant")),
        scanner_baseline=_scanner_baseline_from_dict(d.get("scanner_baseline")),
        environment_anomalies=d.get("environment_anomalies", []),
    )


def save_manifest(
    experiment_id: str, *, base_dir: Path, matrix_cells: list[str], record_count: int
) -> Path:
    _validate_path_segment(experiment_id, field_name="experiment_id")
    manifest_path = base_dir / experiment_id / "manifest.json"
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(
        json.dumps(
            {
                "experiment_id": experiment_id,
                "matrix_cells": matrix_cells,
                "record_count": record_count,
            },
            indent=2,
            sort_keys=True,
        )
    )
    return manifest_path
